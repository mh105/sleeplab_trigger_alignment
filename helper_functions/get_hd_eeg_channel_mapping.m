function channel_mapping = get_hd_eeg_channel_mapping(channel_overrides)
%GET_HD_EEG_CHANNEL_MAPPING Resolve aligned names to HD-EEG source labels.
%   CHANNEL_OVERRIDES is an optional two-column cell array of character
%   vectors: {'C3', 'LL5'; 'M2', 'RD5'}. Unspecified channels keep their
%   defaults. CHANNEL_MAPPING contains aligned names and HD-EEG sources in
%   its first and second columns, respectively.

if nargin < 1
    channel_overrides = {};
end
assert(iscell(channel_overrides) && ismatrix(channel_overrides) && ...
    (isempty(channel_overrides) || size(channel_overrides, 2) == 2) && ...
    all(cellfun(@(name) ischar(name) && isrow(name) && ~isempty(name), ...
    channel_overrides(:))), ...
    'get_hd_eeg_channel_mapping:InvalidOverrides', ...
    ['Channel overrides must be a two-column cell array of nonempty ' ...
     'character row vectors: {aligned name, HD-EEG source; ...}.'])

channel_mapping = { ...
    'Fp1', 'L1'; ...
    'Fp2', 'R1'; ...
    'F3', 'LL2'; ...
    'F4', 'RR2'; ...
    'C3', 'LA2'; ...
    'C4', 'RA2'; ...
    'O1', 'LL11'; ...
    'O2', 'RR11'; ...
    'M1', 'LD6'; ...
    'M2', 'RD6'; ...
    'VEOGL', 'VEOGL'};

if isempty(channel_overrides)
    return
end

override_names = channel_overrides(:, 1);
assert(numel(unique(override_names)) == numel(override_names), ...
    'get_hd_eeg_channel_mapping:DuplicateOverrideChannel', ...
    'Each aligned channel may appear only once in channel overrides.')
[is_supported, mapping_index] = ismember( ...
    override_names, channel_mapping(:, 1));
if ~all(is_supported)
    error('get_hd_eeg_channel_mapping:UnsupportedOverrideChannel', ...
        'Unsupported aligned channel override(s): %s.', ...
        strjoin(override_names(~is_supported), ', '))
end
channel_mapping(mapping_index, 2) = channel_overrides(:, 2);

end
